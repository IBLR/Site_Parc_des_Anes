            <h3>Notre histoire</h3>
            <p>
                C’est en 2008 que Laurence a donné vie au Parc des Anes, au cœur du charmant
                village d’Éguilles, dans le sud de la France. Passionnée depuis toujours par
                les animaux et la nature, elle rêvait de créer un lieu authentique où chacun
                pourrait renouer avec la vie à la ferme et découvrir le monde attachant des ânes.
            </p>
            <p>
                Au départ, le parc n’accueillait que quelques ânes et un petit potager pédagogique.
                Très vite, grâce à l’enthousiasme des visiteurs et à l’implication de bénévoles
                locaux, le projet a pris de l’ampleur. De nouveaux animaux sont arrivés, des ateliers
                ont vu le jour, et le site s’est transformé en un véritable espace de rencontre,
                d’apprentissage et de partage intergénérationnel.
            </p>
            <p>
                Aujourd’hui, le Parc des Anes est reconnu comme un lieu de vie chaleureux, où le
                respect des animaux, la transmission et la convivialité restent au cœur de chaque
                activité. Ici, on prend le temps d’observer, de comprendre, et surtout de s’émerveiller.
            </p>
        </div>

        <div class="home-description">
            <h3>La fondatrice</h3>
            <p>
                Amoureuse des ânes depuis toujours, Laurence a voulu faire de sa passion un projet
                porteur de sens. Educatrice dans l’âme, elle imagine chaque activité pour transmettre
                le respect du vivant et la curiosité du monde rural.
            </p>
            <p>
                Toujours présente sur le terrain, elle accueille les visiteurs avec chaleur et
                enthousiasme, accompagnée de son équipe et de ses fidèles compagnons à grandes oreilles.
            </p>
        </div>
